async def unfile(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    Take one entry out of a collection.

    Filing is exclusive, so this is the only way back: without it a stray
    /link would hide a page from the primary index for good, short of
    editing Telegraph by hand. It also serves as the way to drop a GitHub
    or outward entry, which nothing else could do.

    Replying to a Published message needs no argument at all - that
    message carries both the collection and the page.
    """

    _, _, extras = read_carrier(update.message)

    wanted = command_words(context)
    target = telegraph_path(wanted) if wanted else extras.get("path")

    token, path = await find_site(update, context, "/unfile")

    if not path:
        return

    if not target and not wanted:
        await update.message.reply_text(
            "Reply to a <b>Published</b> message with /unfile, or give the "
            "address of the entry:\n\n"
            "<code>/unfile https://telegra.ph/Some-Page-07-28</code>",
            parse_mode=ParseMode.HTML,
        )
        return

    try:
        page = telegraph("getPage", path=path, return_content="true")

    except Exception as error:
        await update.message.reply_text(f"Could not find that collection:\n{error}")
        return

    head, middle, foot = split_master(page.get("content"))

    listing = middle[0] if middle and middle[0].get("tag") == "ul" else None

    if listing is None:
        await update.message.reply_text(
            f"<b>{page['title']}</b> has nothing in it yet.",
            parse_mode=ParseMode.HTML,
        )
        return

    kept = []
    removed = None

    for item in listing.get("children") or []:

        href = entry_href(item)

        # Matched either as a telegra.ph page or as the exact address of an
        # outward entry, so one command covers both kinds.
        hit = href and (
            (target and telegraph_path(href) == target)
            or (wanted and href.rstrip("/") == wanted.rstrip("/"))
        )

        if hit and removed is None:
            removed = node_text(item).split(INDEX_SEP)[0].strip()
            continue

        kept.append(item)

    if removed is None:
        await update.message.reply_text(
            f"Nothing in <b>{page['title']}</b> points at that.",
            parse_mode=ParseMode.HTML,
        )
        return

    listing["children"] = kept

    try:
        telegraph(
            "editPage",
            access_token=token,
            path=path,
            title=page["title"],
            content=json.dumps(
                head + middle + foot + [kept_marker(page.get("content"))]
            ),
            author_name=page.get("author_name") or "",
            author_url=page.get("author_url") or "",
        )

    except Exception as error:
        await update.message.reply_text(f"Could not save it:\n{error}")
        return

    back = ""

    if is_extra(page.get("content")) and target:
        back = ("\n\nIt is no longer filed, so /site will list it in your "
                "primary index again.")

    await update.message.reply_text(
        f"<b>{removed}</b> removed from {page['title']}.{back}"
        + carrier_link("page", token, site=path),
        parse_mode=ParseMode.HTML,
        disable_web_page_preview=True,
    )


async def retire(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    Take a collection out of service.

    Telegraph cannot delete a page, so the marker is replaced instead. A
    retired index is skipped by everything that looks for one, and is
    still never listed as an article. The page itself stays where it is.
    """

    token, path = await find_site(update, context, "/retire")

    if not path:
        return

    try:
        page = telegraph("getPage", path=path, return_content="true")

    except Exception as error:
        await update.message.reply_text(f"Could not find it:\n{error}")
        return

    content = page.get("content")

    if not is_extra(content):
        await update.message.reply_text(
            "That is your primary collection, so it cannot be retired - "
            "everything you publish is listed there.\n\n"
            "Run /collections and reply to a curated one instead."
        )
        return

    head, middle, foot = split_master(content)

    try:
        telegraph(
            "editPage",
            access_token=token,
            path=path,
            title=page["title"],
            content=json.dumps(
                head + middle + foot
                + [{"tag": "p", "children": [RETIRED_MARK]}]
            ),
            author_name=page.get("author_name") or "",
            author_url=page.get("author_url") or "",
        )

    except Exception as error:
        await update.message.reply_text(f"Could not retire it:\n{error}")
        return

    await update.message.reply_text(
        f"<b>{page['title']}</b> is retired.\n\n"
        "It no longer appears in /collections and nothing will write to it. "
        "The page itself still exists - Telegraph cannot delete one - so its "
        "link keeps working for anyone who has it.\n\n"
        f"{SITE_URL}#{path}",
        parse_mode=ParseMode.HTML,
        disable_web_page_preview=True,
    )


async def revise(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    Path comes from an argument, from the carrier on a Published message,
    or from any telegra.ph URL in the message being replied to.
    """

    token = token_for(update, context)

    path = telegraph_path(" ".join(context.args)) if context.args else None

    source = update.message.reply_to_message

    if not path and source:

        _, _, extras = read_carrier(update.message)

        path = extras.get("path")

        if not path:
            found = re.search(r"https?://telegra\.ph/\S+", source.text or "")
            path = telegraph_path(found.group(0)) if found else None

    if not token or not path:
        await update.message.reply_text(
            "Reply to a <b>Published</b> message with <code>/revise</code> "
            "and Telepatch finds both the page and the token.\n\n"
            "Otherwise: reply to your pinned identity with "
            "<code>/revise &lt;telegra.ph url&gt;</code>.",
            parse_mode=ParseMode.HTML,
        )
        return

    await prompt_revise(update.message, token, path)


