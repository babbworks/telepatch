async def find_site(update, context, command):
    """
    The index path for a command that edits it. Replying to the pinned Site
    message supplies it for free; otherwise it has to be hunted for.
    Returns (token, path) with either possibly None, having already replied.
    """

    token = token_for(update, context)

    if not token:
        await update.message.reply_text(
            token_hint(command),
            parse_mode=ParseMode.HTML,
        )
        return None, None

    _, _, extras = read_carrier(update.message)

    path = extras.get("site")

    if not path:
        notice = await update.message.reply_text("Finding your index…")
        scanned = await asyncio.to_thread(scan_pages, token)
        indexes = list_indexes(scanned)
        await notice.delete()

        if not indexes:
            await update.message.reply_text(
                f"You have no index yet. Run /site first, then {command}."
            )
            return token, None

        # With several collections there is no safe guess to make. /about
        # and /footer overwrite prose, so picking the wrong one destroys
        # writing rather than merely surprising somebody.
        if len(indexes) > 1:
            await update.message.reply_text(
                f"You have {len(indexes)} collections, so {command} needs to "
                "know which one.\n\nRun /collections and reply to the one you "
                f"mean with {command}.",
            )
            return token, None

        path = indexes[0]["path"]

    return token, path


