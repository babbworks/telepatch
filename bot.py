async def publish(message, token, anonymous, override=None, site=None):
    """
    createPage does not inherit account defaults, so the byline is read
    and forwarded here - or deliberately withheld when anonymous, or
    replaced for this page only when an override rode in on the carrier.
    """

    try:
        title, categories, content = split_post(message)

    except ValueError as error:
        await message.reply_text(str(error))
        return

    author_name = ""
    author_url = ""

    if anonymous:
        # Skip the account read entirely so the byline is never even fetched.
        pass

    elif override is not None:
        author_name, author_url = override

    else:

        try:
            info = get_account_info(token)

        except Exception as error:
            await message.reply_text(f"That token did not work:\n{error}")
            return

        author_name = info.get("author_name") or info.get("short_name") or ""
        author_url = info.get("author_url") or ""

    try:
        page = telegraph(
            "createPage",
            access_token=token,
            title=title,
            author_name=author_name,
            author_url=author_url,
            content=json.dumps(content),
        )

    except Exception as error:
        await message.reply_text(f"Could not publish:\n{error}")
        return

    byline = author_name or "no byline"

    tagline = f" · {', '.join(categories)}" if categories else ""

    # A curated collection is not enumerated by /site, so a page written
    # for one has to be put there now or it would never appear.
    added = ""

    if site:
        try:
            words = page_words(content)

            index_title = await asyncio.to_thread(
                insert_entry,
                token, site, page["url"], title, categories,
                page_excerpt(content),
                max(1, round(words / WORDS_PER_MINUTE)),
            )
            added = f"\nAdded to <b>{index_title}</b>."

        except Exception as error:
            added = (
                f"\nCould not add it to that collection: {error}\n"
                "The page itself is published and safe."
            )

    extras = {"path": page["path"]}

    if site:
        extras["site"] = site

    # The carrier here means a reply of "/revise" to this message needs no
    # arguments - both the token and the page path come out of it.
    await message.reply_text(
        f"<b>Published.</b> ({byline}{tagline}){added}\n\n{page['url']}\n\n"
        "Reply to this message with /revise to change it."
        + carrier_link("page", token, **extras),
        parse_mode=ParseMode.HTML,
        disable_web_page_preview=True,
    )

    await send_menu(message, token)


ISO_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")


def read_index_dates(content):
    """
    Recover {path: iso date} from an existing master post.

    Telegraph exposes no publication date, so the master post is where a
    date first gets written down - and rebuilding must not lose it. The
    record lives in the publisher's own public page rather than in any
    store of ours, which keeps the bot stateless while still remembering.
    """

    dates = {}

    def walk(nodes):

        for node in nodes or []:

            if not isinstance(node, dict):
                continue

            kids = node.get("children") or []

            anchor = next(
                (k for k in kids
                 if isinstance(k, dict) and k.get("tag") == "a"),
                None,
            )

            if anchor and (anchor.get("attrs") or {}).get("href"):

                meta = "".join(k for k in kids if isinstance(k, str))
                found = ISO_DATE.search(meta)
                path = telegraph_path(anchor["attrs"]["href"])

                if found and path:
                    dates[path] = found.group(0)

                continue

            walk(kids)

    walk(content)

    return dates


def is_index(content):
    """
    True if this page is one of our generated indexes, current or retired.
    Such pages are never listed as articles.
    """

    text = " ".join(node_text(n) for n in content or [])

    return any(mark in text for mark in INDEX_MARKS)


def scan_pages(token):
    """
    Fetch every page with its content, once.

    The bot holds the token, so it can enumerate pages the public API will
    not. One pass serves both jobs that need it - finding the existing
    index, and building the new one.

    Runs in a worker thread: it is a few hundred blocking calls at worst.
    """

    listing = telegraph("getPageList", access_token=token, limit=INDEX_LIMIT)

    scanned = []

    for page in listing.get("pages", []):

        try:
            full = telegraph(
                "getPage", path=page["path"], return_content="true"
            )

        except Exception:
            # A page that will not load simply gets no categories.
            full = {}

        scanned.append((page, full.get("content")))

    return scanned


def pick_master(scanned):
    """
    The primary index, if any. getPageList is newest first, so the first
    hit is the current one.

    Curated collections are skipped: /site enumerates the account into the
    primary alone, and an account that has never made a second collection
    behaves exactly as it did before they existed.
    """

    for page, content in scanned:

        text = " ".join(node_text(n) for n in content or [])

        if MASTER_MARK in text and RETIRED_MARK not in text \
                and EXTRA_FIELD not in text:
            return page["path"], page.get("title")

    return None, None


def list_indexes(scanned):
    """
    Every live index on the account, the primary first.
    """

    found = []

    for page, content in scanned:

        text = " ".join(node_text(n) for n in content or [])

        if MASTER_MARK not in text or RETIRED_MARK in text:
            continue

        found.append({
            "path": page["path"],
            "title": page.get("title") or page["path"],
            "extra": EXTRA_FIELD in text,
        })

    found.sort(key=lambda index: index["extra"])

    return found


def read_masthead(content):
    """
    The publisher's own prose from the top of the master post.

    /site regenerates the whole page, so an introduction typed by hand would
    vanish on the next rebuild unless it is read back first. Same principle
    as the dates: the master post is the record, and the bot remembers
    nothing between runs.
    """

    return split_master(content)[0]


def split_master(content):
    """
    Split a master post into (masthead, list, footer).

    The generated list sits in the middle; the publisher's own prose sits
    above it and below it. Splitting three ways lets either be replaced
    without regenerating the other or the list between them.
    """

    nodes = list(content or [])
    at = None

    for i, node in enumerate(nodes):

        if not isinstance(node, dict):
            continue

        if node.get("tag") == "ul" or node_text(node).strip() == EMPTY_NOTICE:
            at = i
            break

    if at is None:
        return nodes, [], []

    def keep(node):
        return not any(m in node_text(node) for m in INDEX_MARKS)

    return (
        [n for n in nodes[:at] if keep(n)],
        [nodes[at]],
        [n for n in nodes[at + 1:] if keep(n)],
    )


def read_external(content):
    """
    Index entries that are not Telegraph pages, kept verbatim.

    /site regenerates the list from getPageList, which only knows this
    account's Telegraph pages. A GitHub link added by hand would be wiped
    on the next rebuild, so it is read back first — the same read-before-
    write the dates, masthead and footer already need.
    """

    kept = []

    for node in split_master(content)[1]:

        if not isinstance(node, dict) or node.get("tag") != "ul":
            continue

        for item in node.get("children", []):

            if not isinstance(item, dict):
                continue

            kids = item.get("children", [])

            anchor = next(
                (k for k in kids
                 if isinstance(k, dict) and k.get("tag") == "a"),
                None,
            )

            if not anchor:
                continue

            href = (anchor.get("attrs") or {}).get("href", "")

            if not href or href.startswith("/") or "telegra.ph" in href:
                continue

            text = "".join(k for k in kids if isinstance(k, str))
            found = ISO_DATE.search(text)

            kept.append({"node": item, "date": found.group(0) if found else ""})

    return kept


def read_byline(content):
    """
    The byline mode recorded on the marker line, or the default.
    """

    for node in content or []:

        text = node_text(node)

        if MASTER_MARK not in text:
            continue

        found = re.search(r"byline=(\w+)", text)

        if found and found.group(1) in BYLINE_MODES:
            return found.group(1)

    return BYLINE_DEFAULT


def marker_node(mode=BYLINE_DEFAULT, extra=False):
    """
    The one line the bot writes for itself, carrying the site's settings.
    """

    fields = f"byline={mode}"

    if extra:
        fields += f" {EXTRA_FIELD}"

    return {"tag": "p", "children": [f"{MASTER_MARK} {fields}"]}


def is_retired(content):
    """
    True if this page has been taken out of service, however that was
    done. /retire replaces the marker outright, but retiring by hand in
    the Telegraph editor leaves the original line and adds this one beside
    it, so the whole page is checked rather than the marker alone.
    """

    return any(RETIRED_MARK in node_text(node) for node in content or [])


def kept_marker(content, mode=None):
    """
    The marker line for a page being rewritten.

    Five different commands rewrite an index and each one rebuilds this
    line. Every one of them has to carry across what it did not come to
    change, or editing the footer of a collection would quietly demote it
    to the primary - or bring a retired one back, since split_master
    strips both marks and only one would be written back.
    """

    if is_retired(content):
        return {"tag": "p", "children": [RETIRED_MARK]}

    return marker_node(mode or read_byline(content), extra=is_extra(content))


def is_extra(content):
    """
    True for a curated collection, False for the primary or for anything
    that is not an index at all.
    """

    for node in content or []:

        text = node_text(node)

        if MASTER_MARK in text:
            return EXTRA_FIELD in text

    return False


def read_footer(content):
    """
    The publisher's own closing note, kept across rebuilds like the masthead.
    """

    return split_master(content)[2]


def entry_href(item):
    """
    The address an index entry points at, or None if it is not an entry.
    """

    if not isinstance(item, dict) or item.get("tag") != "li":
        return None

    for child in item.get("children") or []:

        if isinstance(child, dict) and child.get("tag") == "a":
            return (child.get("attrs") or {}).get("href")

    return None


def claimed_paths(scanned):
    """
    The pages filed into a curated collection.

    The primary is the inbox and a collection is a folder: filing a page
    moves it. Membership needs no marker of its own because it is already
    written down - in the list of the collection that claims it - and
    scan_pages has fetched every one of those lists already.

    Retired collections claim nothing, or retiring one would strand its
    pages outside every index.
    """

    filed = set()

    for _, content in scanned:

        text = " ".join(node_text(n) for n in content or [])

        if MASTER_MARK not in text or RETIRED_MARK in text:
            continue

        if EXTRA_FIELD not in text:
            continue

        _, middle, _ = split_master(content)
        listing = middle[0] if middle and middle[0].get("tag") == "ul" else None

        for item in (listing or {}).get("children") or []:

            href = entry_href(item)
            path = telegraph_path(href) if href else None

            # Only pages on telegra.ph can be filed. A GitHub or outward
            # entry was never in the account listing to begin with.
            if path and "github.com" not in (href or ""):
                filed.add(path)

    return filed


def build_index(scanned, master_path=None, known_dates=None,
                masthead=None, footer=None, byline=BYLINE_DEFAULT,
                external=None, filed=None):
    """
    Lay the account's articles out as the content of one master post.

    Every generated index is skipped, not just the one being rewritten -
    otherwise a stray index from an earlier run appears as an article.
    Pages filed into a curated collection are skipped too: they have been
    moved, not copied.
    """

    known_dates = known_dates or {}
    filed = filed or set()
    today = date.today().isoformat()

    entries = []

    for page, content in scanned:

        if page["path"] == master_path or is_index(content):
            continue

        if page["path"] in filed:
            continue

        categories = page_categories(content)
        is_nav = NAV_CATEGORY in [c.lower() for c in categories]

        words = page_words(content)

        entries.append(
            {
                "title": page.get("title") or page["path"],
                "url": page["url"],
                "path": page["path"],
                "categories": categories,
                # First time a page is indexed it is dated today, and that
                # date is carried forward by every later rebuild.
                "date": known_dates.get(page["path"], today),
                # Nav pages never appear in the index, so they get neither.
                "excerpt": "" if is_nav else page_excerpt(content),
                "minutes": 0 if is_nav else max(1, round(words / WORDS_PER_MINUTE)),
            }
        )

    # getPageList is newest first, so a stable sort by date keeps that order
    # within a day while putting newer days on top.
    entries.sort(key=lambda e: e["date"], reverse=True)

    items = []

    for entry in entries:

        children = [
            {
                "tag": "a",
                "attrs": {"href": entry["url"]},
                "children": [entry["title"]],
            }
        ]

        # Everything before the <br> is machine-read: date, reading time,
        # categories. Everything after is the excerpt. Both halves still
        # read as an ordinary sentence on telegra.ph.
        meta = INDEX_SEP + entry["date"]

        if entry["minutes"]:
            meta += f" · {entry['minutes']} min"

        if entry["categories"]:
            meta += " · " + ", ".join(entry["categories"])

        children.append(meta)

        if entry["excerpt"]:
            children.append({"tag": "br"})
            children.append(entry["excerpt"])

        items.append({"date": entry["date"], "node": {"tag": "li", "children": children}})

    # Hand-added entries pointing elsewhere keep their place by date.
    items.extend(external or [])
    items.sort(key=lambda i: i["date"], reverse=True)
    items = [i["node"] for i in items]

    content = list(masthead or [])

    content.append(
        {"tag": "ul", "children": items} if items
        else {"tag": "p", "children": [EMPTY_NOTICE]}
    )

    content.extend(footer or [])
    content.append(marker_node(byline))

    return entries, content


async def rebuild_site(message, token, master_path=None, title=None):
    """
    Create the master post, or rewrite it in place when one already exists.
    """

    notice = await message.reply_text(
        "Reading your pages…" if master_path else "Building your index…"
    )

    try:
        info = get_account_info(token)

    except Exception as error:
        await notice.edit_text(f"That token did not work:\n{error}")
        return

    try:
        scanned = await asyncio.to_thread(scan_pages, token)

    except Exception as error:
        await notice.edit_text(f"Could not read your pages:\n{error}")
        return

    # Rewrite the existing index rather than adding another. Telegraph cannot
    # delete pages, so creating one per run would litter the account forever.
    found_path, found_title = pick_master(scanned)

    if not master_path:
        master_path = found_path

    existing_title = next(
        (p.get("title") for p, _ in scanned if p["path"] == master_path),
        None,
    )

    # A rebuild keeps the name it already has unless a new one is given.
    site_title = (
        title or existing_title or info.get("short_name") or "Telepatch"
    )

    # Read what the old page recorded before overwriting it: the dates, and
    # any introduction the publisher wrote above the list.
    old = next((c for p, c in scanned if p["path"] == master_path), None)

    known_dates = read_index_dates(old)
    masthead = read_masthead(old)
    footer = read_footer(old)

    # A curated collection is a list somebody made on purpose. Enumerating
    # the account into it would replace their choices with everything.
    curated = is_extra(old)
    filed_count = 0

    if curated:
        head, middle, foot = split_master(old)
        content = head + middle + foot + [kept_marker(old)]

        # Shaped like build_index's entries so the summary can count them.
        listed = (middle[0].get("children") if middle else None) or []
        entries = [
            {"categories": []} for node in listed
            if isinstance(node, dict) and node.get("tag") == "li"
        ]

    else:
        filed = claimed_paths(scanned)

        entries, content = build_index(
            scanned, master_path, known_dates, masthead, footer,
            read_byline(old), read_external(old), filed
        )

        # Said out loud, always. A page quietly missing from a rebuild that
        # was run for some other reason is how trust in this goes.
        filed_count = sum(
            1 for page, page_content in scanned
            if page["path"] in filed and not is_index(page_content)
        )

    byline = info.get("author_name") or info.get("short_name") or ""

    try:
        if master_path:
            page = telegraph(
                "editPage",
                access_token=token,
                path=master_path,
                title=site_title,
                content=json.dumps(content),
                author_name=byline,
                author_url=info.get("author_url") or "",
            )

        else:
            page = telegraph(
                "createPage",
                access_token=token,
                title=site_title,
                content=json.dumps(content),
                author_name=byline,
                author_url=info.get("author_url") or "",
            )

    except Exception as error:
        await notice.edit_text(f"Could not save the index:\n{error}")
        return

    nav = sum(1 for e in entries if NAV_CATEGORY in
              [c.lower() for c in e["categories"]])

    tags = sorted({
        c for e in entries for c in e["categories"]
        if c.lower() != NAV_CATEGORY
    })

    await notice.delete()

    sent = await message.reply_text(
        f"<b>{site_title}</b> is live.\n"
        + ("Rewrote your existing index.\n" if master_path else
           "New index created.\n")
        + "\n"
        f"{SITE_URL}#{page['path']}\n\n"
        + (f"{len(entries)} entries · curated by hand\n" if curated else
           f"{len(entries) - nav} posts · {nav} nav pages · "
           f"{len(tags)} categories\n"
           + (f"{filed_count} filed in collections, left out\n"
              if filed_count else ""))
        + (f"{', '.join(tags)}\n" if tags else "")
        + "\nAnyone can open that link - it carries no token.\n"
        "Reply to this message with /site after publishing to refresh it."
        + carrier_link("page", token, site=page["path"]),
        parse_mode=ParseMode.HTML,
        disable_web_page_preview=True,
    )

    try:
        await sent.pin(disable_notification=True)

    except Exception:
        pass


async def revise_page(message, token, path):
    """
    editPage clears author_name and author_url when they are not sent, so
    the current byline is read back and re-supplied. Omitting it would
    silently strip the byline off an existing article.
    """

    try:
        title, categories, content = split_post(message)

    except ValueError as error:
        await message.reply_text(str(error))
        return

    try:
        current = telegraph("getPage", path=path, return_content="false")

    except Exception as error:
        await message.reply_text(f"Could not find that page:\n{error}")
        return

    try:
        page = telegraph(
            "editPage",
            access_token=token,
            path=path,
            title=title,
            content=json.dumps(content),
            author_name=current.get("author_name") or "",
            author_url=current.get("author_url") or "",
        )

    except Exception as error:
        await message.reply_text(f"Could not update:\n{error}")
        return

    await message.reply_text(
        f"<b>Updated.</b>\n\n{page['url']}\n\n"
        "Reply to this message with /revise to change it again."
        + carrier_link("page", token, path=path),
        parse_mode=ParseMode.HTML,
        disable_web_page_preview=True,
    )


